export const dictionaries: Record<Locale, Partial<Record<Key, string>>> = { en, si, ta };

export type TranslationKey = Key;

/** Looks up a key, falling back to English and then to the key itself. */
export function translate(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  const raw = dictionaries[locale]?.[key] ?? en[key] ?? String(key);
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

/** Picks the right language variant of a product/category name. */
export function localizedName(
  locale: Locale,
  item: { name: string; name_si?: string | null; name_ta?: string | null },
): string {
  if (locale === 'si' && item.name_si) return item.name_si;
  if (locale === 'ta' && item.name_ta) return item.name_ta;
  return item.name;
}
